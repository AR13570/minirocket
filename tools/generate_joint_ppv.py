"""Generate fixed-width Numba pooling kernels from a single counting template."""
import argparse
from pathlib import Path

DEFAULT_OUTPUT = Path(__file__).resolve().parents[1] / 'code' / '_joint_ppv_simd_kernels.py'
BLOCK_SIZE = 8


def generate():
    blocks = []
    for width in range(1, BLOCK_SIZE + 1):
        bindings = '\n'.join(f'    bias{i} = biases[start + {i}]\n    count{i} = np.int32(0)'
                             for i in range(width))
        counting = '\n'.join(f'        count{i} = np.int32(count{i} + np.int32(value > bias{i}))'
                             for i in range(width))
        outputs = '\n'.join(f'    output[start + {i}] = count{i} / len(responses)'
                            for i in range(width))
        iteration = ('    for position in range(len(responses)):\n        value = responses[position]'
                     if width <= 4 else '    for value in responses:')
        blocks.append(f'''@njit(cache=True, fastmath=True)
def _pool_{width}(responses, biases, start, output):
{bindings}
{iteration}
{counting}
{outputs}''')
    dispatch = '\n'.join(f'    {"if" if width == 1 else "elif"} remainder == {width}:\n'
                         f'        _pool_{width}(responses, biases, start, output)'
                         for width in range(1, BLOCK_SIZE))
    dispatcher = f'''@njit(cache=True)
def _pool_joint(responses, biases, start, count, output):
    # Fixed scalar int32 reductions permit SIMD and bound register pressure.
    end = start + count
    while start + {BLOCK_SIZE} <= end:
        _pool_{BLOCK_SIZE}(responses, biases, start, output)
        start += {BLOCK_SIZE}
    remainder = end - start
{dispatch}


@njit(cache=True)
def ppv_joint(responses, biases):
    """Count arbitrary numbers of strict-threshold PPVs in supplied order."""
    output = np.empty(len(biases), dtype=np.float32)
    _pool_joint(responses, biases, 0, len(biases), output)
    return output'''
    header = '''"""Generated by tools/generate_joint_ppv.py; edit that template, not this file."""
import numpy as np
from numba import njit


'''
    return header + '\n\n\n'.join(blocks + [dispatcher]) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument('--check', action='store_true', help='Fail if regeneration is needed; do not write')
    args = parser.parse_args(argv)
    source = generate()
    if args.check:
        if not args.output.exists() or args.output.read_text() != source:
            parser.exit(1, f'Regenerate pooling kernels: {args.output}\n')
        print(f'Generated pooling kernels are current: {args.output}')
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(source)
        print(f'Generated pooling kernels: {args.output}')


if __name__ == '__main__':
    main()
